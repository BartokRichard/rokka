export function translate(text: string, locale: Locale): string {
  if (locale === "hu") return text;
  const exact = ro[text];
  if (exact) return exact;
  if (text.includes(" – ")) {
    return text.split(" – ").map((part) => ro[part] ?? part).join(" – ");
  }

  return text
    .replace(/(\d+) termék/g, "$1 produse")
    .replace(/(\d+) kép/g, "$1 imagini")
    .replace(/(\d+) kedvenc/g, "$1 favorite")
    .replace(/(\d+) rontól/g, "de la $1 RON")
    .replace(/(\d+) ron hiányzik az ingyenes szállításhoz\./g, "Mai lipsesc $1 RON pentru livrare gratuită.")
    .replace(/(\d+) ron felett a szállítás ingyenes\./g, "Livrarea este gratuită peste $1 RON.")
    .replace(/ megjelenítve$/, " afișate")
    .replace(/ megye$/, " județ")
    .replace(/^Polár:/, "Polar:")
    .replace(/^Pamut:/, "Bumbac:")
    .replace(/^Vízálló:/, "Impermeabil:")
    .replace(/^Szoptatós:/, "Pentru alăptare:")
    .replace(/^Várandós:/, "Pentru sarcină:")
    .replace(/^Kombinált:/, "Combinat:");
}
